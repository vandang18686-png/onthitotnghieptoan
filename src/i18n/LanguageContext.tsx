/** Translate a Vietnamese source string (teacher admin area). Falls back to the Vietnamese text. */
export const tr = (vi: string): string => (currentLang === 'en' ? ADMIN_EN[vi] ?? vi : vi);
/** tr() with {placeholders} filled in. */
export const trf = (vi: string, vars: Record<string, string | number>): string =>
  Object.entries(vars).reduce((s, [k, v]) => s.replace(`{${k}}`, String(v)), tr(vi));

