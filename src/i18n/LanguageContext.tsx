export type TKey = keyof typeof DICT.vi;
type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: TKey, vars?: Record<string, string | number>) => string };
const LangCtx = createContext<Ctx | null>(null);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem('tnthpt_lang') as Lang | null;
    return saved === 'en' || saved === 'vi' ? saved : navigator.language.startsWith('vi') ? 'vi' : 'en';
  });
  currentLang = lang;
  const setLang = (l: Lang) => { setLangState(l); localStorage.setItem('tnthpt_lang', l); };
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const t = useCallback<Ctx['t']>((k, vars) => {
    let s: string = DICT[lang][k] ?? DICT.vi[k];
    if (vars) for (const [key, v] of Object.entries(vars)) s = s.replace(`{${key}}`, String(v));
    return s;
  }, [lang]);
  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
};

export const useLang = () => {
  const c = useContext(LangCtx);
  if (!c) throw new Error('useLang must be used inside LanguageProvider');
  return c;
};
